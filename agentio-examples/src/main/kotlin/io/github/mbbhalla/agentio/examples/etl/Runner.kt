package io.github.mbbhalla.agentio.examples.etl

import io.github.mbbhalla.agentio.core.common.JsonSchemaUtil
import io.github.mbbhalla.agentio.core.model.LLM
import io.github.mbbhalla.agentio.data.model.DomainModel
import io.github.mbbhalla.agentio.data.model.TableName
import kotlinx.coroutines.runBlocking
import org.slf4j.LoggerFactory
import java.nio.file.Path
import java.time.Instant
import kotlin.io.path.createDirectories
import kotlin.io.path.name
import kotlin.io.path.writeText

/**
 * ETL from CSV files into a DuckDB database defined by an Open Data Contract:
 *
 * 1. Target: [DomainModel.fromOdcs] reads the engine-neutral contract, and the workspace builds it as an
 *    empty DuckDB database that enforces its types, keys and checks.
 * 2. Middle layer: [EtlPipeline] has a planner agent map the sources onto target tables, then a SQL-writer
 *    agent write and prove each table's load with tools that run against DuckDB.
 * 3. Output: the loads become `etl.sql`, which is replayed into a fresh DuckDB to prove it works on its own.
 */
internal object Runner {
    private val LOG = LoggerFactory.getLogger(Runner::class.java)
    private val LLM_USED = LLM.ANTHROPIC_CLAUDE_OPUS_5_5_CROSS_REGION_INFERENCE

    fun run(
        contract: Path,
        sourceDirectory: Path,
        outputDirectory: Path,
    ): EtlRun =
        runBlocking {
            val model = DomainModel.fromOdcs(listOf(contract))
            val workspace = EtlWorkspace(model, SourceFiles.of(sourceDirectory))
            LOG.info("Target: {} tables from {}; sources: {}", model.tables.size, contract.name, workspace.sources.names)

            val planner = EtlPlannerAgenticFunction.create(workspace, LLM_USED)
            val pipeline =
                EtlPipeline(
                    workspace = workspace,
                    planner = { input -> planner.invoke(input).map { it.output } },
                    sqlWriterFor = { references ->
                        val writer = EtlSqlWriterAgenticFunction.create(workspace, references, LLM_USED)
                        SqlWriter { input -> writer.invoke(input).map { it.output } }
                    },
                )
            val run = pipeline.run().getOrThrow()

            outputDirectory.createDirectories()
            outputDirectory
                .resolve(PLAN_FILE)
                .writeText(JsonSchemaUtil.json.encodeToString(LoadPlan.serializer(), run.plan))
            val script =
                EtlScript.of(
                    workspace,
                    run,
                    header =
                        listOf(
                            "Generated by the AgentIO ODCS ETL example at ${Instant.now()} with ${LLM_USED.id}.",
                            "Target contract: ${contract.name}; sources: ${workspace.sources.directory}.",
                            "Run against an empty database: duckdb target.duckdb < $SCRIPT_FILE",
                        ),
                )
            outputDirectory.resolve(SCRIPT_FILE).writeText(script.render())
            val replayed = script.replay()
            val mismatched = run.loaded.filter { replayed[TableName(it.table)] != it.rows.toLong() }
            check(mismatched.isEmpty()) { "Replaying ${SCRIPT_FILE} loads different row counts for ${mismatched.map { it.table }}" }

            report(run, replayed, outputDirectory)
            run
        }

    private fun report(
        run: EtlRun,
        replayed: Map<TableName, Long>,
        outputDirectory: Path,
    ) {
        LOG.info("=== Result")
        run.loaded.forEach {
            LOG.info(
                "  {} rows into {} (attempt {}); script replay: {} rows",
                it.rows,
                it.table,
                it.attempts,
                replayed[TableName(it.table)],
            )
        }
        run.failure?.let { failure ->
            LOG.error("  {} could not be loaded; later steps were not attempted. Attempts:", failure.table)
            failure.attemptErrors.forEachIndexed { i, e -> LOG.error("    {}. {}", i + 1, e) }
        }
        run.orphans.forEach { (reference, count) -> LOG.info("  {}: {} orphaned rows", reference, count) }
        LOG.info("Plan: {}; ETL script: {}", outputDirectory.resolve(PLAN_FILE), outputDirectory.resolve(SCRIPT_FILE))
    }

    private const val PLAN_FILE = "load-plan.json"
    private const val SCRIPT_FILE = "etl.sql"
}

fun main(args: Array<String>) {
    require(args.size == 3) { "Usage: <contract .odcs.yaml> <source CSV directory> <output directory>" }
    val run = Runner.run(Path.of(args[0]), Path.of(args[1]), Path.of(args[2]))
    check(run.succeeded) { "The ETL did not complete; see the result above" }
}
